import argparse
import os
import re
import sys
import urllib.request

UPSTREAM = "https://raw.githubusercontent.com/mdqinc/SDL_GameControllerDB/master/gamecontrollerdb.txt"
HEADER_PATH = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "mkfw_joystick_gamedb.h"))
MARK_BEGIN = "/* BEGIN GENERATED gamedb */"
MARK_END   = "/* END GENERATED gamedb */"
BUTTONS = "a b x y leftshoulder rightshoulder back start guide leftstick rightstick dpup dpdown dpleft dpright".split()
AXES = "leftx lefty rightx righty lefttrigger righttrigger".split()


def fetch(url):
	with urllib.request.urlopen(url, timeout=60) as r:
		return r.read().decode("utf-8")


def pack_source(source):
	match = re.fullmatch(r"([+-]?)([bah])(\d+)(?:\.(\d+))?(~?)", source)
	if not match:
		return 0
	# Preserve Doozer binding polarity, including its treatment of trailing ~.
	sign, kind, index, mask, _ = match.groups()
	index = int(index)
	if kind == "h":
		if index != 0 or mask is None or not 0 < int(mask) <= 15:
			return 0
		return 0xc0 | int(mask)
	if index >= 32:
		return 0
	if kind == "b":
		return 0x40 | index
	return 0x80 | index | (0x20 if sign == "-" else 0)


def parse(text):
	entries = []
	seen = set()
	for raw in text.splitlines():
		fields = raw.strip().split(",")
		if len(fields) < 3 or not re.fullmatch(r"[0-9a-fA-F]{32}", fields[0]):
			continue
		mapping = dict(field.split(":", 1) for field in fields[2:] if ":" in field)
		if mapping.get("platform") != "Linux":
			continue
		guid = bytes.fromhex(fields[0])
		key = (int.from_bytes(guid[4:6], "little"), int.from_bytes(guid[8:10], "little"))
		if key in seen or key == (0, 0):
			continue
		seen.add(key)
		buttons = [pack_source(mapping.get(name, "")) for name in BUTTONS]
		axes = [pack_source(mapping.get(name, "")) for name in AXES]
		entries.append((*key, buttons, axes))
	return entries


def emit(entries, source_url):
	lines = [MARK_BEGIN]
	lines.append("// Generated by tools/gen_joystick_gamedb.py from " + source_url)
	lines.append(f"// Entries: {len(entries)} Linux vendor/product pairs; Windows uses XInput.")
	lines.append("struct mkfw_gamedb_record {")
	lines.append("\tuint16_t vendor_id;")
	lines.append("\tuint16_t product_id;")
	lines.append("\tuint8_t buttons[MKFW_GAMEPAD_BUTTON_LAST];")
	lines.append("\tuint8_t axes[MKFW_GAMEPAD_AXIS_LAST];")
	lines.append("};")
	lines.append("")
	lines.append("static const struct mkfw_gamedb_record mkfw_gamecontrollerdb_data[] = {")
	for vendor, product, buttons, axes in entries:
		button_data = ", ".join(f"0x{binding:02x}" for binding in buttons)
		axis_data = ", ".join(f"0x{binding:02x}" for binding in axes)
		lines.append(f"\t{{0x{vendor:04x}, 0x{product:04x}, {{{button_data}}}, {{{axis_data}}}}},")
	lines.append("};")
	lines.append(MARK_END)
	return "\n".join(lines) + "\n"


def splice(file_text, generated):
	i = file_text.find(MARK_BEGIN)
	j = file_text.find(MARK_END)
	if i < 0 or j < 0:
		raise SystemExit(f"missing markers in {HEADER_PATH}")
	if j < i:
		raise SystemExit("END marker found before BEGIN marker")
	j_end = j + len(MARK_END)
	return file_text[:i] + generated.rstrip() + file_text[j_end:]


def main():
	ap = argparse.ArgumentParser()
	ap.add_argument("--dry-run", action="store_true", help="print the generated block to stdout instead of writing")
	ap.add_argument("--from-file", metavar="PATH", help="read upstream DB from a local file instead of fetching")
	ap.add_argument("--url", default=UPSTREAM, help="override upstream URL")
	args = ap.parse_args()

	if args.from_file:
		with open(args.from_file, "r", encoding="utf-8") as f:
			text = f.read()
		source = args.from_file
	else:
		print(f"Fetching {args.url}", file=sys.stderr)
		text = fetch(args.url)
		source = args.url

	entries = parse(text)
	if not entries:
		raise SystemExit("no entries matched after filtering; refusing to overwrite header")

	generated = emit(entries, source)

	if args.dry_run:
		sys.stdout.write(generated)
		return

	with open(HEADER_PATH, "r", encoding="utf-8") as f:
		original = f.read()
	new = splice(original, generated)
	tmp = HEADER_PATH + ".tmp"
	with open(tmp, "w", encoding="utf-8") as f:
		f.write(new)
	os.replace(tmp, HEADER_PATH)
	print(f"Wrote {len(entries)} entries to {HEADER_PATH}", file=sys.stderr)


if __name__ == "__main__":
	main()
